import { NestFactory } from '@nestjs/core';
import { AppModule } from './app.module';
import { ValidationPipe } from '@nestjs/common';
import { DocumentBuilder, SwaggerModule } from '@nestjs/swagger';

async function bootstrap() {
  const app = await NestFactory.create(AppModule);

  app.setGlobalPrefix('api/v1');

  app.enableCors({
    origin: process.env.FRONTEND_URL || 'http://localhost:3002',
    credentials: true,
  });

  app.useGlobalPipes(
    new ValidationPipe({
      whitelist: true,
      transform: true,
      forbidNonWhitelisted: true,
    }),
  );

  const config = new DocumentBuilder()
    .setTitle('Pixlo Recipe Sharing Platform API')
    .setDescription('Culinary community API with exact rational scaling, meal planning, and shopping list aggregation')
    .setVersion('1.0')
    .addBearerAuth()
    .build();

  const document = SwaggerModule.createDocument(app, config);
  SwaggerModule.setup('api/docs', app, document);

  const port = process.env.PORT || 4002;
  await app.listen(port);
  console.log(`[Pixlo Recipes Backend] running on http://localhost:${port}/api/v1`);
  console.log(`[Pixlo Recipes OpenAPI] documentation at http://localhost:${port}/api/docs`);
}

bootstrap();
