import request from 'supertest';
import { createApp } from '../src/app';
import { memoryStore } from '../src/store/memory-store';

describe('CMS Platform API End-to-End Lifecycle', () => {
  const app = createApp();

  beforeEach(() => {
    memoryStore.clear();
  });

  it('should return health status', async () => {
    const res = await request(app).get('/health');
    expect(res.status).toBe(200);
    expect(res.body.service).toBe('08-cms-platform-wordpress-alternative');
    expect(res.body.port).toBe(4008);
  });

  it('should create dynamic content schema and query it', async () => {
    // 1. Create Schema for 'products'
    const schemaPayload = {
      name: 'Product',
      singularName: 'product',
      pluralName: 'products',
      fields: [
        { name: 'title', type: 'string', required: true, min: 2 },
        { name: 'price', type: 'number', required: true, min: 0 },
        { name: 'category', type: 'enumeration', enumValues: ['Hardware', 'Accessories', 'Software'], defaultValue: 'Hardware' },
        { name: 'inStock', type: 'boolean', defaultValue: true },
      ],
    };

    const schemaRes = await request(app).post('/api/v1/admin/schemas').send(schemaPayload);
    expect(schemaRes.status).toBe(201);
    expect(schemaRes.body.slug).toBe('products');

    // 2. Insert valid dynamic content entry
    const entry1 = {
      title: 'Mechanical Gaming Keyboard',
      price: 129.99,
      category: 'Hardware',
    };
    const entryRes = await request(app).post('/api/v1/content/products').send(entry1);
    expect(entryRes.status).toBe(201);
    expect(entryRes.body.id).toBeDefined();
    expect(entryRes.body.title).toBe('Mechanical Gaming Keyboard');
    expect(entryRes.body.inStock).toBe(true); // default value
    expect(entryRes.body.slug).toBe('mechanical-gaming-keyboard'); // Auto-generated by SEO plugin!

    const entryId = entryRes.body.id;

    // 3. Insert second entry
    await request(app).post('/api/v1/content/products').send({
      title: 'USB-C Cable 2m',
      price: 14.50,
      category: 'Accessories',
    });

    // 4. Query entries with dynamic filter: price[$gt]=50
    const queryRes = await request(app).get('/api/v1/content/products?price[$gt]=50');
    expect(queryRes.status).toBe(200);
    expect(queryRes.body.data.length).toBe(1);
    expect(queryRes.body.data[0].title).toBe('Mechanical Gaming Keyboard');

    // 5. Publish entry
    const publishRes = await request(app).post(`/api/v1/content/products/${entryId}/publish`);
    expect(publishRes.status).toBe(200);
    expect(publishRes.body.status).toBe('PUBLISHED');
    expect(publishRes.body.publishedAt).toBeDefined();

    // 6. Upload media asset
    const sampleBase64 = Buffer.from('fake-image-png-content').toString('base64');
    const mediaRes = await request(app).post('/api/v1/media/upload').send({
      fileName: 'product-shot.png',
      mimeType: 'image/png',
      base64Content: sampleBase64,
      altText: 'Keyboard hero shot',
    });
    expect(mediaRes.status).toBe(201);
    expect(mediaRes.body.fileName).toBe('product-shot.png');
    expect(mediaRes.body.formats.thumbnail).toBeDefined();

    // 7. Generate API token
    const tokenRes = await request(app).post('/api/v1/tokens').send({
      name: 'Mobile App Read Token',
      tokenType: 'READ_ONLY',
    });
    expect(tokenRes.status).toBe(201);
    expect(tokenRes.body.token).toContain('cms_live_');
  });

  it('should reject invalid entries violating dynamic schema constraints', async () => {
    // Register schema
    await request(app).post('/api/v1/admin/schemas').send({
      name: 'Event',
      singularName: 'event',
      pluralName: 'events',
      fields: [
        { name: 'name', type: 'string', required: true, min: 5 },
        { name: 'capacity', type: 'number', required: true, min: 1 },
      ],
    });

    // Try posting invalid entry (name too short, missing capacity)
    const res = await request(app).post('/api/v1/content/events').send({
      name: 'Tech',
    });

    expect(res.status).toBe(400);
    expect(res.body.error).toBe('Validation Error');
    expect(res.body.details.some((d: any) => d.field === 'name')).toBe(true);
    expect(res.body.details.some((d: any) => d.field === 'capacity')).toBe(true);
  });
});
